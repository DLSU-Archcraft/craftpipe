#!/usr/bin/env python3
"""Write the README's list of game differences from the file the parity
tests enforce (tests/parity/known_differences.json).

    python tools/render_differences.py
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
SOURCE = REPO / "tests/parity/known_differences.json"
README = REPO / "README.md"
START = "<!-- differences:start (generated by tools/render_differences.py) -->"
END = "<!-- differences:end -->"


def _field(entry, name):
    return entry[name] if isinstance(entry, dict) else getattr(entry, name)


def render(entries) -> str:
    lines = []
    for entry in entries:
        title = _field(entry, "title").rstrip(".")
        line = f"- **{title}.** {_field(entry, 'explanation')}"
        if _field(entry, "established") == "documented":
            line += " *(Minecraft's side is taken from documentation, not measured.)*"
        if _field(entry, "with_java_rules") == "fixed":
            line += " *Removed by `craftpipe_java_rules`.*"
        else:
            line += " *Still present with `craftpipe_java_rules`.*"
        lines.append(line)
    return "\n".join(lines) if lines else "None recorded."


def main() -> int:
    text = README.read_text()
    if START not in text or END not in text:
        print("README.md has no differences markers", file=sys.stderr)
        return 1
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(f"{head}{START}\n{render(json.loads(SOURCE.read_text()))}\n{END}{tail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
